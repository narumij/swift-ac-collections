#!/usr/bin/env python3
"""Extract the raw bytes of the measured inner closure (permutation sequential batched)
from objdump output of CI artifacts, check they are identical across binaries, and emit
closure_bytes.inc (GNU as .byte lines) plus closure_bytes.h (C array for runtime checks).

Usage: extract_bytes.py OUTDIR ASM [ASM ...]
The closure is located by its mangled symbol header line in the objdump output.
Trailing alignment padding after the final ud2 is excluded (222 bytes)."""
import hashlib, re, sys

SYM = "$s20CollectionsBenchmark0B0V10BenchmarksE014addPermutationC0yyFyAA5TimerVzcSgSicfU1_yAGzcfU_yyXEfU_"
LENGTH = 222      # bytes up to and including the last ud2 (0x0f 0x0b)
LOOP_OFFSET = 0x80

def extract(path):
    out, start, inside = bytearray(), None, False
    pat = re.compile(r"^\s*([0-9a-f]+):\t((?:[0-9a-f]{2}[ \t])+)")
    for line in open(path, errors="replace"):
        if line.endswith("<" + SYM + ">:\n"):
            inside, start = True, int(line.split()[0], 16)
            continue
        if inside:
            if line.strip() == "" or line.endswith(">:\n"):
                break
            m = pat.match(line)
            if m:
                out += bytes.fromhex(re.sub(r"\s", "", m.group(2)))
    if start is None:
        sys.exit(f"symbol not found in {path}")
    return start, bytes(out[:LENGTH]), bytes(out)

outdir, paths = sys.argv[1], sys.argv[2:]
results = [(p, *extract(p)) for p in paths]
ref = results[0][2]
for p, start, body, full in results:
    print(f"{p}\n  entry={start:#x} loop={start+LOOP_OFFSET:#x} loop_mod32={(start+LOOP_OFFSET)%32} "
          f"loop_mod64={(start+LOOP_OFFSET)%64} sha256={hashlib.sha256(body).hexdigest()} "
          f"identical_to_first={body == ref} trailing={full[LENGTH:].hex()}")
if any(r[2] != ref for r in results):
    sys.exit("closure bytes differ between binaries")
assert ref[-2:] == b"\x0f\x0b", "expected ud2 at end"
assert ref[LOOP_OFFSET:LOOP_OFFSET + 6] == bytes.fromhex("f3420f6f14d6"), "expected movdqu at +0x80"

with open(f"{outdir}/closure_bytes.inc", "w") as f:
    shown = [p.split("PerformanceCI/", 1)[-1] for p in paths]
    f.write(f"/* {LENGTH} bytes of {SYM}\n   sha256 {hashlib.sha256(ref).hexdigest()}\n"
            "   extracted by extract_bytes.py from Benchmarks/_Artifacts/PerformanceCI/:\n"
            + "".join(f"     {s}\n" for s in shown) + "*/\n")
    for i in range(0, LENGTH, 16):
        f.write("    .byte " + ", ".join(f"0x{b:02x}" for b in ref[i:i + 16]) + "\n")
with open(f"{outdir}/closure_bytes.h", "w") as f:
    f.write(f"/* generated by extract_bytes.py; sha256 {hashlib.sha256(ref).hexdigest()} */\n")
    f.write(f"#define CLOSURE_LENGTH {LENGTH}\n#define CLOSURE_LOOP_OFFSET 0x{LOOP_OFFSET:x}\n")
    f.write("static const unsigned char closure_reference[CLOSURE_LENGTH] = {\n")
    for i in range(0, LENGTH, 12):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in ref[i:i + 12]) + ",\n")
    f.write("};\n")
print("wrote closure_bytes.inc and closure_bytes.h")
