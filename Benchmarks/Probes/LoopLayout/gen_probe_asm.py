#!/usr/bin/env python3
"""Generate probe_copies.S: identical copies of the 222-byte closure, each placed at
(4096-byte boundary + pad) so that the vector loop (+0x80) starts at loop_mod64 == pad.
Every copy has its own 4096-byte slot, so copies differ only in the in-page offset.

Usage: gen_probe_asm.py CLOSURE_BYTES_INC OUTPUT_S"""
import sys

if len(sys.argv) != 3:
    sys.exit(__doc__)
inc_path, out_path = sys.argv[1], sys.argv[2]
# Copy table. Duplicated pads are same-placement controls.
#   pad 32 = placement of the fast CI binaries (loop mod64 32)
#   pad 48 = placement of the slow CI binaries (loop mod64 48)
PADS = [0, 8, 16, 24, 32, 40, 48, 56, 32, 48]

inc = open(inc_path).read()
lines = [
    "/* generated by gen_probe_asm.py -- do not edit by hand */",
    "#if defined(__APPLE__)",
    "#define SYM(x) _##x",
    "#define FUNC_TYPE(x)",
    "#define FUNC_SIZE(x)",
    "#else",
    "#define SYM(x) x",
    "#define FUNC_TYPE(x) .type x, @function",
    "#define FUNC_SIZE(x) .size x, . - x",
    "#endif",
    "",
    "    .text",
]
for i, pad in enumerate(PADS):
    name = f"probe_copy_{i}"
    lines += [
        "",
        f"/* copy {i}: entry at 4096*k + {pad}, vector loop mod64 = {pad} */",
        "    .p2align 12, 0xcc",
        f"    .fill {pad}, 1, 0xcc" if pad else "    /* no pad */",
        f"    .globl SYM({name})",
        f"    FUNC_TYPE(SYM({name}))",
        f"SYM({name}):",
        inc.rstrip(),
        f"    FUNC_SIZE(SYM({name}))",
    ]
lines += [
    "",
    "    .data",
    "    .p2align 3",
    "    .globl SYM(probe_copy_pads)",
    "SYM(probe_copy_pads):",
    "    .quad " + ", ".join(str(p) for p in PADS),
    "    .globl SYM(probe_copy_count)",
    "SYM(probe_copy_count):",
    f"    .quad {len(PADS)}",
    "",
    "#if !defined(__APPLE__)",
    "    .section .note.GNU-stack,\"\",@progbits",
    "#endif",
    "",
]
with open(out_path, "w") as f:
    f.write("\n".join(lines))
print(f"wrote {out_path} with {len(PADS)} copies: pads {PADS}")
