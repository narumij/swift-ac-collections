#!/usr/bin/env python3
"""OPS-160 isolated read experiment: load an explicit-order fixture into SQLite and read it back.

Experiment only. Nothing here reads or writes the live Registry, Milestones/, Studio, Inbox or any shared DB; the default
database is in memory. No update or numbering API (out of scope).

Model (TASK_REGISTRY_V3_DESIGN.md「既決事項の回収と設計調査の結論」):
- nodes: one ID space for every kind (task, card, gate, start, end). START-<v>/END-<v> are generated by the loader in the
  same transaction; the fixture cannot write them.
- versions: explicit position from the fixture order (no folder comparator). version_members: card order within a version.
  version_gates: at most one gate per version; the gate ID is only an identifier and never names the destination.
- skeleton (derived, not stored): START -> cards -> END per version; END -> gate; gate -> START of the next version in the
  explicit order when one exists. A version without a gate is not connected to the next one; a gate of the last version
  ends there.
- graph_edges: 'management' (parent -> child), 'progress' (prerequisite -> successor between tasks) and 'milestone'
  (task <-> milestone node) are kept apart. Cycles are refused within management, and within progress + milestone +
  skeleton taken together (the order in which work can happen); a cycle across the management and progress graphs is not a
  cycle.
- focus: the version the default read starts from. It only selects the read range: nothing about arrival (DONE) is
  derived from it, and the loader stores no milestone state at all.
- attributes (OPS-161): task condition/detail/permanent/group, card and gate name and detail, the card's DONE box as
  written (recordedDone; gates have none), edge flow and constraint. Stored values only; no value is derived.
- provenance: where each row came from in the fixture, returned apart from the structure and scoped to what was returned.
"""
import json
import sqlite3
import sys

SCHEMA = """
PRAGMA foreign_keys = ON;
CREATE TABLE nodes (id TEXT PRIMARY KEY, kind TEXT NOT NULL CHECK (kind IN ('task','card','gate','start','end')), name TEXT NOT NULL);
CREATE TABLE tasks (id TEXT PRIMARY KEY REFERENCES nodes(id), state TEXT NOT NULL, owner TEXT NOT NULL, item TEXT NOT NULL,
  condition TEXT NOT NULL, detail TEXT NOT NULL, permanent INTEGER NOT NULL CHECK (permanent IN (0, 1)), task_group TEXT);
CREATE TABLE milestone_details (id TEXT PRIMARY KEY REFERENCES nodes(id), detail TEXT NOT NULL,
  recorded_done INTEGER CHECK (recorded_done IN (0, 1)));  -- cards: the DONE box as written; gates: NULL. Never derived from HEAD
CREATE TABLE versions (name TEXT PRIMARY KEY, position INTEGER NOT NULL UNIQUE);
CREATE TABLE version_members (version TEXT NOT NULL REFERENCES versions(name), node TEXT NOT NULL UNIQUE REFERENCES nodes(id),
  position INTEGER NOT NULL, UNIQUE (version, position));
CREATE TABLE version_gates (version TEXT PRIMARY KEY REFERENCES versions(name), gate TEXT NOT NULL UNIQUE REFERENCES nodes(id));
CREATE TABLE graph_edges (graph TEXT NOT NULL CHECK (graph IN ('management','progress','milestone')),
  prerequisite TEXT NOT NULL REFERENCES nodes(id), successor TEXT NOT NULL REFERENCES nodes(id), flow TEXT, constraint_text TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (graph, prerequisite, successor), CHECK (prerequisite <> successor));
CREATE TABLE focus (one INTEGER PRIMARY KEY CHECK (one = 1), version TEXT NOT NULL REFERENCES versions(name));
CREATE TABLE provenance (subject TEXT PRIMARY KEY, origin TEXT NOT NULL);
"""


class Refused(ValueError):
    """The fixture breaks a structural rule; nothing was stored."""


def connect(path=':memory:'):
    conn = sqlite3.connect(path, isolation_level=None)
    conn.executescript(SCHEMA)
    return conn


def _cycle(edges):
    """A node on a cycle of the directed edges, or None."""
    out = {}
    for a, b in edges:
        out.setdefault(a, []).append(b)
    state = {}
    for start in sorted(out):
        if state.get(start):
            continue
        stack = [(start, iter(out.get(start, ())))]
        state[start] = 1
        while stack:
            node, it = stack[-1]
            nxt = next(it, None)
            if nxt is None:
                state[node] = 2
                stack.pop()
            elif state.get(nxt) == 1:
                return nxt
            elif not state.get(nxt):
                state[nxt] = 1
                stack.append((nxt, iter(out.get(nxt, ()))))
    return None


def load(conn, fixture, origin='fixture'):
    """Store the fixture in one transaction. Any failure after BEGIN rolls everything back: a structural refusal raises
    Refused, an integrity error becomes Refused, and anything else (a malformed fixture, e.g. a missing field) is re-raised
    as it is, with the transaction closed."""
    conn.execute('BEGIN')
    try:
        _load(conn, fixture, origin)
        conn.execute('COMMIT')
    except sqlite3.IntegrityError as error:
        conn.execute('ROLLBACK')
        raise Refused(f'integrity: {error}') from None
    except BaseException:
        conn.execute('ROLLBACK')
        raise


def _node(conn, nid, kind, name, origin):
    if conn.execute('SELECT 1 FROM nodes WHERE id = ?', (nid,)).fetchone():
        raise Refused(f'duplicate ID {nid} ({origin})')
    conn.execute('INSERT INTO nodes VALUES (?, ?, ?)', (nid, kind, name))
    conn.execute('INSERT INTO provenance VALUES (?, ?)', ('node:' + nid, origin))


def _load(conn, fx, origin):
    for i, t in enumerate(fx.get('tasks', [])):
        _node(conn, t['id'], 'task', t['item'], f'{origin}:tasks[{i}]')
        if not isinstance(t['permanent'], bool):
            raise Refused(f'tasks[{i}]: permanent must be true or false')
        conn.execute('INSERT INTO tasks VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
                     (t['id'], t['state'], t['owner'], t['item'], t['condition'], t['detail'], int(t['permanent']), t['group']))
    for vi, v in enumerate(fx['versions']):
        name = v['name']
        if conn.execute('SELECT 1 FROM versions WHERE name = ?', (name,)).fetchone():
            raise Refused(f'duplicate version {name}')
        conn.execute('INSERT INTO versions VALUES (?, ?)', (name, vi))
        conn.execute('INSERT INTO provenance VALUES (?, ?)', ('version:' + name, f'{origin}:versions[{vi}]'))
        _node(conn, 'START-' + name, 'start', 'START-' + name, f'{origin}:versions[{vi}] (generated)')
        _node(conn, 'END-' + name, 'end', 'END-' + name, f'{origin}:versions[{vi}] (generated)')
        for ci, card in enumerate(v.get('cards', [])):
            _node(conn, card['id'], 'card', card['name'], f'{origin}:versions[{vi}].cards[{ci}]')
            conn.execute('INSERT INTO version_members VALUES (?, ?, ?)', (name, card['id'], ci))
            if not isinstance(card['recordedDone'], bool):
                raise Refused(f'versions[{vi}].cards[{ci}]: recordedDone must be true or false')
            conn.execute('INSERT INTO milestone_details VALUES (?, ?, ?)', (card['id'], card['detail'], int(card['recordedDone'])))
        if v.get('gate'):
            _node(conn, v['gate']['id'], 'gate', v['gate']['name'], f'{origin}:versions[{vi}].gate')
            conn.execute('INSERT INTO version_gates VALUES (?, ?)', (name, v['gate']['id']))
            conn.execute('INSERT INTO milestone_details VALUES (?, ?, NULL)', (v['gate']['id'], v['gate']['detail']))
    for graph in ('management', 'progress', 'milestone'):
        for i, e in enumerate(fx.get(graph, [])):
            ends = [conn.execute('SELECT kind FROM nodes WHERE id = ?', (x,)).fetchone() for x in (e['prerequisite'], e['successor'])]
            if not all(ends):
                missing = [x for x, k in zip((e['prerequisite'], e['successor']), ends) if not k]
                raise Refused(f'{graph}[{i}]: missing endpoint {", ".join(missing)}')
            kinds = [k[0] for k in ends]
            if graph in ('management', 'progress') and kinds != ['task', 'task']:
                raise Refused(f'{graph}[{i}]: both endpoints must be tasks, got {kinds}')
            if graph == 'milestone' and kinds.count('task') != 1:
                raise Refused(f'milestone[{i}]: exactly one endpoint must be a task, got {kinds}')
            conn.execute('INSERT INTO graph_edges VALUES (?, ?, ?, ?, ?)',
                         (graph, e['prerequisite'], e['successor'], e.get('flow'), e.get('constraint', '')))
            conn.execute('INSERT INTO provenance VALUES (?, ?)', (f"edge:{graph}:{e['prerequisite']}->{e['successor']}", f'{origin}:{graph}[{i}]'))
    if fx.get('focus') is not None:
        if not conn.execute('SELECT 1 FROM versions WHERE name = ?', (fx['focus'],)).fetchone():
            raise Refused(f"focus names an unknown version {fx['focus']}")
        conn.execute('INSERT INTO focus VALUES (1, ?)', (fx['focus'],))
    management = conn.execute("SELECT prerequisite, successor FROM graph_edges WHERE graph = 'management'").fetchall()
    if (n := _cycle(management)):
        raise Refused(f'management cycle through {n}')
    work = conn.execute("SELECT prerequisite, successor FROM graph_edges WHERE graph IN ('progress','milestone')").fetchall() + skeleton(conn)
    if (n := _cycle(work)):
        raise Refused(f'progress cycle through {n} (progress + milestone + skeleton)')


def skeleton(conn):
    """Derived structure edges, in order: START -> cards -> END per version, END -> gate, gate -> next START."""
    versions = [r[0] for r in conn.execute('SELECT name FROM versions ORDER BY position')]
    gates = dict(conn.execute('SELECT version, gate FROM version_gates'))
    edges = []
    for i, v in enumerate(versions):
        chain = ['START-' + v] + [r[0] for r in conn.execute('SELECT node FROM version_members WHERE version = ? ORDER BY position', (v,))] + ['END-' + v]
        edges += list(zip(chain, chain[1:]))
        if v in gates:
            edges.append(('END-' + v, gates[v]))
            if i + 1 < len(versions):
                edges.append((gates[v], 'START-' + versions[i + 1]))
    return edges


def _locations(conn):
    """Version of every milestone node; tasks are placed by the versions of the milestone nodes they connect to."""
    where = {}
    for name, in conn.execute('SELECT name FROM versions'):
        where['START-' + name] = where['END-' + name] = name
    where.update(dict(conn.execute('SELECT node, version FROM version_members')))
    where.update({g: v for v, g in conn.execute('SELECT version, gate FROM version_gates')})
    tasks = {}
    for a, b in conn.execute("SELECT prerequisite, successor FROM graph_edges WHERE graph = 'milestone'"):
        task, other = (a, b) if a not in where else (b, a)
        tasks.setdefault(task, set()).add(where[other])
    return where, tasks


def read(conn, scope='current'):
    """Read the stored structure. scope 'all' returns everything; 'current' (default) the versions from the focus on,
    the tasks connected to them, and every edge that touches them -- endpoints outside the range are returned as
    boundary references with their location (ID, kind, versions; no attributes), never dropped or rewired.
    Parts: ids (with the stored attributes of the returned nodes), relations (pairs), edges (the same edges with flow and
    constraint), order, range, sources (provenance of the returned nodes, boundary references, edges and versions only).
    Experiment, not a full-fidelity migration: no Markdown position (raw/sourceLine) and no derived state are returned."""
    if scope not in ('current', 'all'):
        raise ValueError(f"unknown read scope {scope!r}: use 'current' or 'all'")
    focus = conn.execute('SELECT version FROM focus').fetchone()
    versions = [r[0] for r in conn.execute('SELECT name FROM versions ORDER BY position')]
    if scope == 'all' or focus is None:
        in_versions = versions
    else:
        in_versions = versions[versions.index(focus[0]):]
    where, task_places = _locations(conn)
    kinds = dict(conn.execute('SELECT id, kind FROM nodes'))
    in_range = {n for n, v in where.items() if v in in_versions}
    in_range |= {t for t, vs in task_places.items() if vs & set(in_versions)}
    if scope == 'all' or focus is None:
        in_range |= {n for n, k in kinds.items() if k == 'task'}  # unplaced tasks are part of the whole view only
    relations = {'skeleton': [list(e) for e in skeleton(conn) if e[0] in in_range or e[1] in in_range]}
    edges = {}
    for graph in ('management', 'progress', 'milestone'):
        edges[graph] = [{'prerequisite': a, 'successor': b, 'flow': f, 'constraint': c} for a, b, f, c in
                        conn.execute('SELECT prerequisite, successor, flow, constraint_text FROM graph_edges WHERE graph = ? ORDER BY prerequisite, successor', (graph,))
                        if a in in_range or b in in_range]
        relations[graph] = [[e['prerequisite'], e['successor']] for e in edges[graph]]
    touched = {x for edges in relations.values() for e in edges for x in e}
    boundary = sorted(({'id': x, 'kind': kinds[x], 'versions': sorted(task_places.get(x, ())) if kinds[x] == 'task' else [where[x]]}
                       for x in touched - in_range), key=lambda b: b['id'])
    order = {v: [r[0] for r in conn.execute('SELECT node FROM version_members WHERE version = ? ORDER BY position', (v,))] for v in in_versions}
    tasks = {r[0]: {'state': r[1], 'owner': r[2], 'item': r[3], 'condition': r[4], 'detail': r[5], 'permanent': bool(r[6]), 'group': r[7]}
             for r in conn.execute('SELECT id, state, owner, item, condition, detail, permanent, task_group FROM tasks ORDER BY id') if r[0] in in_range}
    milestones = {r[0]: {'name': r[1], 'detail': r[2], **({} if r[3] is None else {'recordedDone': bool(r[3])})}
                  for r in conn.execute('SELECT m.id, n.name, m.detail, m.recorded_done FROM milestone_details m JOIN nodes n ON n.id = m.id ORDER BY m.id') if r[0] in in_range}
    wanted = {'node:' + n for n in in_range | {b['id'] for b in boundary}} | {'version:' + v for v in in_versions} | \
             {f"edge:{g}:{e['prerequisite']}->{e['successor']}" for g, es in edges.items() for e in es}
    gates = {v: g for v, g in conn.execute('SELECT version, gate FROM version_gates') if v in in_versions}
    return {
        'ids': {'nodes': sorted(in_range), 'kinds': {n: kinds[n] for n in sorted(in_range)}, 'tasks': tasks, 'milestones': milestones},
        'relations': relations,
        'edges': edges,
        'order': {'versions': in_versions, 'cards': order, 'gates': gates},
        'range': {'scope': scope, 'focus': focus[0] if focus else None, 'boundary': boundary},
        'sources': {k: v for k, v in conn.execute('SELECT subject, origin FROM provenance ORDER BY subject') if k in wanted},
    }


def main(argv):
    if len(argv) not in (2, 3) or (len(argv) == 3 and argv[2] not in ('current', 'all')):
        print('usage: registry_v3_read.py FIXTURE.json [current|all]', file=sys.stderr)
        return 2
    with open(argv[1], encoding='utf-8') as f:
        fixture = json.load(f)
    conn = connect()
    try:
        load(conn, fixture, argv[1])
        print(json.dumps(read(conn, argv[2] if len(argv) == 3 else 'current'), ensure_ascii=False, indent=1))
        return 0
    except Refused as error:
        print('refused:', error, file=sys.stderr)
        return 1
    finally:
        conn.close()


if __name__ == '__main__':
    sys.exit(main(sys.argv))
