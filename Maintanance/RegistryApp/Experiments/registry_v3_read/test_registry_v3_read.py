#!/usr/bin/env python3
"""OPS-160 tests: explicit-order fixtures -> in-memory SQLite -> read, against expected values written by hand from the
structural DESIGN (Milestones/DESIGN.md) and TASK_REGISTRY_V3_DESIGN.md, not generated by the experiment.

Where the current reader (sync.py build()) and the DESIGN agree, the same fixture is also written as a throwaway
Registry/Milestones tree in a temporary directory and read by the current reader; the common contract (IDs, task fields,
the three graphs, card order, gates and the derived skeleton) must be equal. Where they are known to differ (gate ID used
as the destination, a missing gate, a terminal gate), the expected value is the DESIGN's; the current reader's refusal is
recorded as KNOWN DEVIATION and is never counted as the expected result.

Run: python3 -B Maintanance/RegistryApp/Experiments/registry_v3_read/test_registry_v3_read.py -v
"""
import copy
import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import registry_v3_read as r3  # noqa: E402

BASE = json.loads((HERE / 'fixtures' / 'base.json').read_text(encoding='utf-8'))
SYNC = HERE.parent.parent / 'sync.py'
REPORT = []  # (case, expected-from, note) printed at the end


def fixture(change=None):
    fx = copy.deepcopy(BASE)
    if change:
        change(fx)
    return fx


def loaded(fx):
    conn = r3.connect()
    r3.load(conn, fx)
    return conn


def version(fx, name):
    return next(v for v in fx['versions'] if v['name'] == name)


# ---- the current reader on a throwaway tree (read only; sync.py itself is not changed) ----

def write_tree(fx, root):
    """The fixture as Registry/Milestones files the current reader understands. File names carry the explicit order."""
    registry = root / 'Maintanance/ProgressV2/TASK_REGISTRY_V2.md'
    registry.parent.mkdir(parents=True)
    rows = ['# Registry', '', '## Task Registry', '', '| ID | 状態 | 担当 | 項目 | 条件 | 正本 |', '| --- | --- | --- | --- | --- | --- |']
    rows += [f"| `{t['id']}` | `{t['state']}` | {t['owner']} | {t['item']} | 条件 | 正本 |" for t in fx['tasks']]
    rows += ['', '## 恒久タスクの親子関係', '', '| 親 | 子 |', '| --- | --- |']
    rows += [f"| `{e['prerequisite']}` | `{e['successor']}` |" for e in fx['management']]
    rows += ['', '## Task precedence', '', '| 後続 | 前提 | Flow | 制約 |', '| --- | --- | --- | --- |']
    rows += [f"| `{e['successor']}` | `{e['prerequisite']}` | `{e['flow']}` | {e.get('constraint', '')} |" for e in fx['progress']]
    rows += ['', '## マイルストーン接続', '', '| 接続元 | 接続先 | 制約 |', '| --- | --- | --- |']
    rows += [f"| `{e['prerequisite']}` | `{e['successor']}` | {e.get('constraint', '')} |" for e in fx['milestone']]
    registry.write_text('\n'.join(rows) + '\n', encoding='utf-8')
    (registry.parent / 'TASK_RULES_V2.md').write_text('`TASK-001`は常設の支援nodeとして`ACTIVE`を保つ。\n', encoding='utf-8')
    ms = root / 'Maintanance/Milestones'
    ms.mkdir(parents=True)
    (ms / 'README.md').write_text('- END-x.y.z は版フォルダごとの集合点で、実ファイルを置かない。\n', encoding='utf-8')
    (ms / 'HEAD.md').write_text(f"# {fx['focus']}\n", encoding='utf-8')
    for v in fx['versions']:
        d = ms / v['name']
        d.mkdir()
        for i, c in enumerate(v['cards']):
            (d / f'{(i + 1) * 10:02d}_card.md').write_text(f"# カード情報\n\n## ID\n\n`{c['id']}`\n\n## 名前\n\n{c['name']}\n\n## 状態\n\n- [ ] DONE\n\n# 正本\n\nこのファイル\n\n# 記録\n", encoding='utf-8')
        if v['gate']:
            g = v['gate']
            (d / f"{g['id']}.md").write_text(f"# カード情報\n\n## ID\n\n`{g['id']}`\n\n## 名前\n\n{g['name']}\n\n# 正本\n\nこのファイル\n", encoding='utf-8')


def current_reader(fx):
    """(common contract, None) or (None, errors) from sync.build() run on a temporary tree."""
    spec = importlib.util.spec_from_file_location('sync_for_ops160', SYNC)
    sync = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sync)
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write_tree(fx, root)
        sync.ROOT = root
        sync.REGISTRY = root / 'Maintanance/ProgressV2/TASK_REGISTRY_V2.md'
        sync.RULES = root / 'Maintanance/ProgressV2/TASK_RULES_V2.md'
        sync.MILESTONES = root / 'Maintanance/Milestones'
        data, errors = sync.build()
    if data is None:
        return None, errors
    cards = {}
    for m in data['milestones']:
        folder = m['gate'].split('/')[2]
        cards.setdefault(folder, [])
        if not m.get('virtual') and not m['id'].startswith('GATE-'):
            cards[folder].append(m['id'])
    registry_rel = [r for r in data['milestoneRelations'] if r['source']['path'].endswith('TASK_REGISTRY_V2.md')]
    chain = [r for r in data['milestoneRelations'] if r['source']['path'].endswith('Milestones/README.md')]
    return {
        'nodes': sorted([t['id'] for t in data['tasks']] + [m['id'] for m in data['milestones']]),
        'tasks': {t['id']: {'state': t['state'], 'owner': t['owner'], 'item': t['item']} for t in data['tasks']},
        'management': sorted([t['parentTask'], t['id']] for t in data['tasks'] if 'parentTask' in t),
        'progress': sorted([e['prerequisite'], e['successor']] for e in data['edges']),
        'milestone': sorted([r['prerequisite'], r['successor']] for r in registry_rel),
        'skeleton': [[r['prerequisite'], r['successor']] for r in chain],
        'cards': cards,
        'gates': {m['gate'].split('/')[2]: m['id'] for m in data['milestones'] if m['id'].startswith('GATE-')},
    }, None


def common(view):
    """The same contract from the experiment's whole read."""
    return {
        'nodes': view['ids']['nodes'],
        'tasks': view['ids']['tasks'],
        'management': view['relations']['management'],
        'progress': view['relations']['progress'],
        'milestone': view['relations']['milestone'],
        'skeleton': view['relations']['skeleton'],
        'cards': view['order']['cards'],
        'gates': view['order']['gates'],
    }


def differences(a, b):
    return sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))


# Expected skeleton of the base fixture, written from the DESIGN by hand:
# START -> cards (file order) -> END -> gate -> next START; the last version has no gate and ends at its END.
BASE_SKELETON = [['START-0.1.0', 'MS-A1'], ['MS-A1', 'MS-A2'], ['MS-A2', 'END-0.1.0'], ['END-0.1.0', 'GATE-0.2.0'], ['GATE-0.2.0', 'START-0.2.0'],
                 ['START-0.2.0', 'MS-B1'], ['MS-B1', 'END-0.2.0'], ['END-0.2.0', 'GATE-0.3.0'], ['GATE-0.3.0', 'START-0.3.0'],
                 ['START-0.3.0', 'END-0.3.0']]


class Structure(unittest.TestCase):
    def test_base_structure_matches_design(self):
        view = r3.read(loaded(fixture()), 'all')
        self.assertEqual(view['relations']['skeleton'], BASE_SKELETON)
        self.assertEqual(view['order']['versions'], ['0.1.0', '0.2.0', '0.3.0'])
        self.assertEqual(view['order']['cards'], {'0.1.0': ['MS-A1', 'MS-A2'], '0.2.0': ['MS-B1'], '0.3.0': []})
        self.assertEqual(view['ids']['kinds']['START-0.1.0'], 'start')
        self.assertEqual(view['ids']['kinds']['GATE-0.2.0'], 'gate')
        REPORT.append(('base structure', 'DESIGN (hand-written)', ''))

    def test_base_common_contract_equals_current_reader(self):
        reader, errors = current_reader(fixture())
        self.assertIsNone(errors)
        mine = common(r3.read(loaded(fixture()), 'all'))
        self.assertEqual(differences(mine, reader), [])
        self.assertEqual(mine['skeleton'], BASE_SKELETON)  # and both equal the hand-written DESIGN value
        REPORT.append(('base common contract', 'current reader = DESIGN', 'nodes, tasks, 3 graphs, skeleton, cards, gates'))

    def test_comparison_detects_a_changed_input(self):
        # negative control: the same comparison fails when the input differs
        reader, _ = current_reader(fixture())
        swapped = fixture(lambda fx: version(fx, '0.1.0')['cards'].reverse())
        self.assertIn('skeleton', differences(common(r3.read(loaded(swapped), 'all')), reader))
        renamed = fixture(lambda fx: fx['tasks'][1].update(owner='別の担当'))
        self.assertEqual(differences(common(r3.read(loaded(renamed), 'all')), reader), ['tasks'])
        REPORT.append(('negative control', '-', 'card swap and owner change are both detected'))

    def test_card_order_change_keeps_ids_and_task_links(self):
        fx = fixture(lambda fx: version(fx, '0.1.0')['cards'].reverse())
        view = r3.read(loaded(fx), 'all')
        self.assertEqual(view['relations']['skeleton'][:3], [['START-0.1.0', 'MS-A2'], ['MS-A2', 'MS-A1'], ['MS-A1', 'END-0.1.0']])
        self.assertIn(['TASK-002', 'MS-A2'], view['relations']['milestone'])
        self.assertEqual(sorted(view['ids']['nodes']), sorted(r3.read(loaded(fixture()), 'all')['ids']['nodes']))
        reader, errors = current_reader(fx)
        self.assertIsNone(errors)
        self.assertEqual(differences(common(view), reader), [])
        REPORT.append(('card order change', 'DESIGN, and current reader agrees', 'file names carry the explicit order'))


class KnownDeviations(unittest.TestCase):
    """The DESIGN is the expected value. The current reader's result is recorded, not used as the expectation."""

    def test_named_gate_is_not_the_destination(self):
        fx = fixture(lambda fx: version(fx, '0.1.0').update(gate={'id': 'GATE-9.9.9', 'name': '9.9.9 リリース'}))
        sk = r3.read(loaded(fx), 'all')['relations']['skeleton']
        self.assertIn(['END-0.1.0', 'GATE-9.9.9'], sk)
        self.assertIn(['GATE-9.9.9', 'START-0.2.0'], sk)  # the next version in order, whatever the gate is called
        reader, errors = current_reader(fx)
        self.assertIsNone(reader)
        self.assertTrue(any('destination folder missing' in e for e in errors), errors)
        REPORT.append(('named gate', 'DESIGN', 'KNOWN DEVIATION: current reader refuses (gate ID read as destination)'))

    def test_missing_gate_leaves_versions_unconnected(self):
        fx = fixture(lambda fx: version(fx, '0.2.0').update(gate=None))
        sk = r3.read(loaded(fx), 'all')['relations']['skeleton']
        self.assertFalse([e for e in sk if e[0] == 'END-0.2.0'], 'END of B has no successor')
        self.assertFalse([e for e in sk if e[1] == 'START-0.3.0'], 'START of C has no predecessor; nothing is connected automatically')
        self.assertIn(['START-0.3.0', 'END-0.3.0'], sk)
        reader, errors = current_reader(fx)
        self.assertIsNone(reader)
        self.assertTrue(any('one connected sequence' in e for e in errors), errors)
        REPORT.append(('missing gate', 'DESIGN', 'KNOWN DEVIATION: current reader refuses (requires one connected path)'))

    def test_terminal_gate_ends_there(self):
        fx = fixture(lambda fx: version(fx, '0.3.0').update(gate={'id': 'GATE-0.4.0', 'name': '0.4.0 リリース'}))
        sk = r3.read(loaded(fx), 'all')['relations']['skeleton']
        self.assertEqual(sk[-1], ['END-0.3.0', 'GATE-0.4.0'])
        self.assertFalse([e for e in sk if e[0] == 'GATE-0.4.0'])
        reader, errors = current_reader(fx)
        self.assertIsNone(reader)
        self.assertTrue(any('destination folder missing' in e for e in errors), errors)
        REPORT.append(('terminal gate', 'DESIGN', 'KNOWN DEVIATION: current reader refuses (destination missing)'))


class FocusAndBoundary(unittest.TestCase):
    def test_focus_selects_the_range_and_keeps_all_data(self):
        conn = loaded(fixture())
        current, whole = r3.read(conn, 'current'), r3.read(conn, 'all')
        self.assertEqual(current['order']['versions'], ['0.2.0', '0.3.0'])
        self.assertEqual(current['ids']['nodes'], ['END-0.2.0', 'END-0.3.0', 'GATE-0.3.0', 'MS-B1', 'START-0.2.0', 'START-0.3.0', 'TASK-003', 'TASK-004'])
        self.assertEqual(len(whole['ids']['nodes']), 5 + 3 + 3 * 2 + 2)  # tasks, cards, START/END, gates
        moved = loaded(fixture(lambda fx: fx.update(focus='0.3.0')))
        self.assertEqual(r3.read(moved, 'all')['ids'], whole['ids'], 'moving the focus deletes nothing and changes no stored value')
        self.assertEqual(r3.read(moved, 'current')['order']['versions'], ['0.3.0'])
        REPORT.append(('focus vs all', 'TASK_REGISTRY_V3_DESIGN expected table', ''))

    def test_focus_derives_no_arrival(self):
        conn = loaded(fixture())
        rows = conn.execute('SELECT * FROM nodes ORDER BY id').fetchall()
        for name in ('0.1.0', '0.3.0'):
            moved = loaded(fixture(lambda fx: fx.update(focus=name)))
            self.assertEqual(moved.execute('SELECT * FROM nodes ORDER BY id').fetchall(), rows)
        columns = {r[1] for t in ('nodes', 'version_members', 'version_gates', 'versions') for r in conn.execute(f'PRAGMA table_info({t})')}
        self.assertFalse(columns & {'state', 'done', 'arrived'}, 'no milestone state is stored or derived')
        self.assertEqual(r3.read(conn, 'all')['ids']['tasks']['TASK-002']['state'], 'DONE', 'task state is stored as given')
        REPORT.append(('focus derives no arrival', 'TASK_REGISTRY_V3_DESIGN', 'HEAD-derived DONE is not reproduced'))

    def test_boundary_endpoints_are_returned_not_dropped(self):
        view = r3.read(loaded(fixture()), 'current')
        self.assertIn(['TASK-002', 'TASK-003'], view['relations']['progress'], 'a progress edge crossing the boundary stays')
        self.assertIn(['GATE-0.2.0', 'START-0.2.0'], view['relations']['skeleton'])
        self.assertEqual(view['range']['boundary'], [{'id': 'GATE-0.2.0', 'kind': 'gate', 'versions': ['0.1.0']},
                                                     {'id': 'TASK-002', 'kind': 'task', 'versions': ['0.1.0']}])
        self.assertNotIn('TASK-005', view['ids']['nodes'], 'an unplaced task is part of the whole view only')
        self.assertIn('TASK-005', r3.read(loaded(fixture()), 'all')['ids']['nodes'])
        REPORT.append(('boundary endpoints', 'TASK_REGISTRY_V3_DESIGN expected table', 'IDs and locations returned; nothing rewired'))

    def test_sources_are_separate_from_structure(self):
        view = r3.read(loaded(fixture()), 'all')
        self.assertEqual(view['sources']['node:MS-A2'], 'fixture:versions[0].cards[1]')
        self.assertEqual(view['sources']['node:START-0.2.0'], 'fixture:versions[1] (generated)')
        self.assertEqual(view['sources']['edge:progress:TASK-002->TASK-003'], 'fixture:progress[0]')
        self.assertNotIn('sources', json.dumps(view['relations']))


class Graphs(unittest.TestCase):
    def test_management_and_progress_are_separate(self):
        view = r3.read(loaded(fixture()), 'all')
        self.assertEqual(view['relations']['management'], [['TASK-001', 'TASK-002']])
        self.assertEqual(view['relations']['progress'], [['TASK-002', 'TASK-003']])
        # a progress edge child -> parent is not a cycle: the graphs are not merged
        crossed = fixture(lambda fx: fx['progress'].append({'prerequisite': 'TASK-002', 'successor': 'TASK-001', 'flow': 'SEQUENCE'}))
        self.assertIn(['TASK-002', 'TASK-001'], r3.read(loaded(crossed), 'all')['relations']['progress'])


class Refusals(unittest.TestCase):
    def refused(self, fx, words):
        conn = r3.connect()
        with self.assertRaises(r3.Refused) as caught:
            r3.load(conn, fx)
        self.assertIn(words, str(caught.exception))
        for table in ('nodes', 'tasks', 'versions', 'version_members', 'version_gates', 'graph_edges', 'focus', 'provenance'):
            self.assertEqual(conn.execute(f'SELECT COUNT(*) FROM {table}').fetchone()[0], 0, f'{table} rolled back')

    def test_duplicate_ids_across_kinds(self):
        self.refused(fixture(lambda fx: version(fx, '0.2.0')['cards'][0].update(id='TASK-003')), 'duplicate ID TASK-003')
        self.refused(fixture(lambda fx: version(fx, '0.1.0')['cards'][0].update(id='START-0.2.0')), 'duplicate ID START-0.2.0')
        self.refused(fixture(lambda fx: version(fx, '0.2.0').update(gate={'id': 'GATE-0.2.0', 'name': 'x'})), 'duplicate ID GATE-0.2.0')
        self.refused(fixture(lambda fx: fx['versions'].append({'name': '0.1.0', 'cards': [], 'gate': None})), 'duplicate version 0.1.0')

    def test_missing_endpoints(self):
        self.refused(fixture(lambda fx: fx['progress'].append({'prerequisite': 'TASK-404', 'successor': 'TASK-003', 'flow': 'SEQUENCE'})), 'missing endpoint TASK-404')
        self.refused(fixture(lambda fx: fx['milestone'].append({'prerequisite': 'TASK-004', 'successor': 'END-9.9.9'})), 'missing endpoint END-9.9.9')
        self.refused(fixture(lambda fx: fx.update(focus='9.9.9')), 'unknown version')

    def test_cycles(self):
        self.refused(fixture(lambda fx: fx['progress'].append({'prerequisite': 'TASK-003', 'successor': 'TASK-002', 'flow': 'SEQUENCE'})), 'progress cycle')
        self.refused(fixture(lambda fx: fx['management'].append({'prerequisite': 'TASK-002', 'successor': 'TASK-001'})), 'management cycle')
        # through the derived skeleton: A's card -> ... -> START-B -> TASK-003 -> A's card
        self.refused(fixture(lambda fx: fx['milestone'].append({'prerequisite': 'TASK-003', 'successor': 'MS-A1'})), 'progress cycle')

    def test_edge_kinds(self):
        self.refused(fixture(lambda fx: fx['progress'].append({'prerequisite': 'TASK-005', 'successor': 'MS-B1', 'flow': 'SEQUENCE'})), 'both endpoints must be tasks')
        self.refused(fixture(lambda fx: fx['milestone'].append({'prerequisite': 'MS-A1', 'successor': 'MS-B1'})), 'exactly one endpoint must be a task')

    def test_malformed_input_rolls_back_and_closes_the_transaction(self):
        # a missing field is not a structural refusal: the original error stays, and nothing is left behind
        for change, error in ((lambda fx: fx['tasks'][1].pop('owner'), KeyError), (lambda fx: fx['versions'][1].pop('name'), KeyError),
                              (lambda fx: fx['milestone'].append({'prerequisite': 'TASK-001'}), KeyError), (lambda fx: fx.update(versions=None), TypeError)):
            conn = r3.connect()
            with self.assertRaises(error):
                r3.load(conn, fixture(change))
            self.assertFalse(conn.in_transaction, 'the transaction is closed')
            for table in ('nodes', 'tasks', 'versions', 'version_members', 'version_gates', 'graph_edges', 'focus', 'provenance'):
                self.assertEqual(conn.execute(f'SELECT COUNT(*) FROM {table}').fetchone()[0], 0, f'{table} rolled back')
            r3.load(conn, fixture())  # the same connection is usable afterwards
            self.assertEqual(len(r3.read(conn, 'all')['ids']['nodes']), 16)

    def test_refusal_closes_the_transaction(self):
        conn = r3.connect()
        with self.assertRaises(r3.Refused):
            r3.load(conn, fixture(lambda fx: fx.update(focus='9.9.9')))
        self.assertFalse(conn.in_transaction)

    def test_unknown_read_scope_is_refused(self):
        conn = loaded(fixture())
        for scope in ('Current', 'al', '', None):
            with self.assertRaises(ValueError):
                r3.read(conn, scope)

    def test_generated_ids_cannot_be_written(self):
        self.refused(fixture(lambda fx: fx['tasks'].append({'id': 'END-0.1.0', 'state': 'ACTIVE', 'owner': 'x', 'item': 'x'})), 'duplicate ID END-0.1.0')


if __name__ == '__main__':
    result = unittest.main(exit=False, verbosity=2 if '-v' in sys.argv else 1).result
    print('\nexpected values by case:')
    for case, source, note in REPORT:
        print(f'- {case}: {source}' + (f' ({note})' if note else ''))
    sys.exit(0 if result.wasSuccessful() else 1)
