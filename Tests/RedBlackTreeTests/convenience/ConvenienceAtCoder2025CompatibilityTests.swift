    func testRedBlackTreeConveniences() throws {
      let numbers: RedBlackTreeSet = [1, 3, 5, 7, 9]

      XCTAssertEqual(numbers.lessThan(4), 3)
      XCTAssertEqual(numbers.lessThanOrEqual(4), 3)
